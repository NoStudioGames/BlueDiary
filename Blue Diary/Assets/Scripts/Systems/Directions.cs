/// <summary>
/// Enum representing the four cardinal directions.
/// </summary>
public enum Directions
{
    /// <summary>
    /// Represents upward direction.
    /// </summary>
    UP, // 0

    /// <summary>
    /// Represents rightward direction.
    /// </summary>
    RIGHT, // 1

    /// <summary>
    /// Represents downward direction.
    /// </summary>
    DOWN, // 2

    /// <summary>
    /// Represents leftward direction.
    /// </summary>
    LEFT // 3
}